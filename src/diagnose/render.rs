//! Output formats for a [`Report`]. `redact` masks the network's own addresses in any of them.
use super::analyze::Report;
use super::facts::Status;
use crate::{
    export::escape_html,
    model::json_string,
    view::{safe, Theme},
};

pub fn text(r: &Report, t: &Theme) -> String {
    let mut out: Vec<String> = r
        .steps
        .iter()
        .map(|s| {
            let code = match s.status {
                Status::Ok => "1;38;5;46",
                Status::Warn => "1;38;5;208",
                Status::Fail => "1;38;5;196",
                Status::Skip => "38;5;245",
                Status::Info => "38;5;75",
            };
            format!(
                "{} {} {}",
                t.paint(code, &format!("{:<5}", s.status.label())),
                t.paint("1;97", &format!("{:<10}", s.name)),
                safe(&s.detail)
            )
        })
        .collect();
    out.push(String::new());
    out.push(format!("{}  {}", t.title("VERDICT"), safe(&r.verdict)));
    if !r.advice.is_empty() {
        out.push(String::new());
        out.push(t.paint("1;38;5;51", "WHAT TO TRY"));
        out.extend(
            r.advice
                .iter()
                .enumerate()
                .map(|(i, a)| format!("  {}. {}", i + 1, safe(a))),
        );
    }
    if !r.also.is_empty() {
        out.push(String::new());
        out.push(t.paint("38;5;245", "ALSO NOTICED"));
        out.extend(r.also.iter().map(|a| format!("  · {}", safe(a))));
    }
    out.join("\n")
}

pub fn json(r: &Report) -> String {
    let steps: Vec<String> = r
        .steps
        .iter()
        .map(|s| {
            format!(
                "{{\"step\":{},\"status\":{},\"detail\":{},\"ms\":{}}}",
                json_string(s.name),
                json_string(s.status.label()),
                json_string(&s.detail),
                s.ms.map_or("null".to_string(), |m| format!("{m:.2}"))
            )
        })
        .collect();
    let list = |v: &[String]| {
        format!(
            "[{}]",
            v.iter()
                .map(|s| json_string(s))
                .collect::<Vec<_>>()
                .join(",")
        )
    };
    format!(
        "{{\"steps\":[{}],\"verdict\":{},\"advice\":{},\"also\":{},\"target\":{}}}",
        steps.join(","),
        json_string(&r.verdict),
        list(&r.advice),
        list(&r.also),
        r.target
            .as_ref()
            .map_or("null".to_string(), |t| json_string(t))
    )
}

fn md_cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

pub fn markdown(r: &Report) -> String {
    let mut out = String::from("# MACORA network diagnosis\n\n");
    if let Some(t) = &r.target {
        out += &format!("Site checked: `{t}`\n\n");
    }
    out += "| Result | Check | Details |\n|---|---|---|\n";
    for s in &r.steps {
        out += &format!(
            "| {} | {} | {} |\n",
            s.status.label(),
            s.name,
            md_cell(&s.detail)
        );
    }
    out += &format!("\n**Verdict:** {}\n", r.verdict);
    if !r.advice.is_empty() {
        out += "\n## What to try\n\n";
        for (i, a) in r.advice.iter().enumerate() {
            out += &format!("{}. {a}\n", i + 1);
        }
    }
    if !r.also.is_empty() {
        out += "\n## Also noticed\n\n";
        for a in &r.also {
            out += &format!("- {a}\n");
        }
    }
    out += "\n_Active checks only: a few pings, TCP connections and DNS lookups, run when you asked. Generated by MACORA._\n";
    safe(&out)
}

pub fn html(r: &Report) -> String {
    let rows: String = r
        .steps
        .iter()
        .map(|s| {
            format!(
                "<tr><td class=\"{c}\">{l}</td><td><b>{n}</b></td><td>{d}</td></tr>\n",
                c = s.status.label().to_lowercase(),
                l = s.status.label(),
                n = escape_html(s.name),
                d = escape_html(&s.detail)
            )
        })
        .collect();
    let list = |title: &str, items: &[String]| {
        if items.is_empty() {
            String::new()
        } else {
            format!(
                "<h2>{title}</h2>\n<ol>\n{}</ol>\n",
                items
                    .iter()
                    .map(|i| format!("<li>{}</li>\n", escape_html(i)))
                    .collect::<String>()
            )
        }
    };
    format!(
        "<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">\n<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">\n<title>MACORA network diagnosis</title>\n<style>\n:root{{--bg:#fff;--fg:#1d1d1f;--mut:#6e6e73;--line:#d2d2d7;--ok:#1a7f37;--warn:#b25000;--fail:#c4262e;--info:#0071e3}}\n@media(prefers-color-scheme:dark){{:root{{--bg:#111;--fg:#f5f5f7;--mut:#a1a1a6;--line:#38383a;--ok:#3fb950;--warn:#ffb340;--fail:#ff6b6b;--info:#2997ff}}}}\nbody{{font:15px/1.5 -apple-system,system-ui,sans-serif;background:var(--bg);color:var(--fg);max-width:60rem;margin:2rem auto;padding:0 1rem}}\ntable{{border-collapse:collapse;width:100%}}td{{border-bottom:1px solid var(--line);padding:.45rem;vertical-align:top}}\ntd.ok{{color:var(--ok)}}td.warn{{color:var(--warn)}}td.fail{{color:var(--fail)}}td.info{{color:var(--info)}}td.skip{{color:var(--mut)}}td:first-child{{font-weight:700;width:4.5rem}}\n.verdict{{border:1px solid var(--line);border-radius:12px;padding:1rem;margin:1.2rem 0}}.sub{{color:var(--mut)}}\n</style></head><body>\n<h1>MACORA network diagnosis</h1>\n{site}<table>\n{rows}</table>\n<div class=\"verdict\"><b>Verdict.</b> {verdict}</div>\n{advice}{also}<p class=\"sub\">Active checks only: a few pings, TCP connections and DNS lookups, run when you asked. Generated by MACORA.</p>\n</body></html>",
        site = r.target.as_ref().map_or(String::new(), |t| format!("<p class=\"sub\">Site checked: <code>{}</code></p>\n", escape_html(t))),
        rows = rows,
        verdict = escape_html(&r.verdict),
        advice = list("What to try", &r.advice),
        also = list("Also noticed", &r.also),
    )
}

/// Masks the network's own addresses (`secrets`, longest first) in already-rendered output.
pub fn redact(mut text: String, secrets: &[String]) -> String {
    for s in secrets {
        let mask = if s.contains(':') { "<IPv6>" } else { "<IPv4>" };
        text = text.replace(s.as_str(), mask);
    }
    text
}
